"""
RouteWise AI – Weather and Safety Agent
Integrates Open-Meteo forecast data with Granite-powered safety assessment.
"""

from __future__ import annotations

import json
import logging
from datetime import date
from typing import Any, Dict, List, Optional

from models.travel_request import TravelRequest
from services.watsonx_service import WatsonxService
from services.weather_service import get_weather_forecast, WeatherForecast

logger = logging.getLogger("routewise.agent.weather")

SYSTEM_CONTEXT = """You are a travel safety and weather advisor for India.
Given weather forecast data, return:
- overall_assessment: one-sentence summary of travel conditions
- safety_level: one of [excellent, good, caution, avoid]
- disruption_days: list of day numbers (1-based) with potentially disruptive weather
- recommendations: list of 3 weather-related packing or planning recommendations
- alternative_suggestion: null or brief note if conditions suggest changes

Respond ONLY with valid JSON. No markdown, no extra text."""


class WeatherAgent:
    def __init__(self, watsonx: WatsonxService) -> None:
        self.watsonx = watsonx

    def analyze(self, request: TravelRequest) -> Dict[str, Any]:
        forecast = get_weather_forecast(
            city=request.destination,
            start_date=request.start_date,
            end_date=request.end_date,
        )

        weather_summary = self._summarize_forecast(forecast)
        prompt = self._build_prompt(request, forecast, weather_summary)

        granite_assessment: Dict[str, Any] = {}
        try:
            result = self.watsonx.generate(prompt, max_tokens=300)
            parsed = self._parse_json(result.text)
            if parsed:
                granite_assessment = parsed
                logger.info("WeatherAgent: Granite assessment complete.")
        except Exception as exc:
            logger.warning("WeatherAgent: Granite unavailable (%s), fallback.", type(exc).__name__)
            granite_assessment = self._fallback_assessment(forecast)

        return {
            "forecast_available": forecast is not None,
            "weather_days": [
                {
                    "date": d.date_str,
                    "max_temp": d.max_temp_c,
                    "min_temp": d.min_temp_c,
                    "precipitation_mm": d.precipitation_mm,
                    "description": d.description,
                    "is_disruptive": d.is_disruptive,
                }
                for d in (forecast.days if forecast else [])
            ],
            "data_source": "Open-Meteo (open-meteo.com)" if forecast else "No data",
            # Disclosure: weather forecast is from Open-Meteo; the safety
            # assessment is AI-generated by IBM Granite and is NOT an official
            # meteorological or safety advisory.
            "data_disclaimer": (
                "Weather forecast sourced from Open-Meteo (open-meteo.com). "
                "Safety assessment is AI-generated by IBM Granite and is not an "
                "official meteorological or travel safety advisory. "
                "Always verify conditions with local authorities before travel."
            ),
            **granite_assessment,
        }

    def _summarize_forecast(self, forecast: Optional[WeatherForecast]) -> str:
        if not forecast or not forecast.days:
            return "No forecast data available."
        disruptive = [d for d in forecast.days if d.is_disruptive]
        avg_max = sum(d.max_temp_c for d in forecast.days) / len(forecast.days)
        return (
            f"{len(forecast.days)} days forecast. "
            f"Avg high: {avg_max:.1f}°C. "
            f"Disruptive weather days: {len(disruptive)}."
        )

    def _build_prompt(self, request: TravelRequest, forecast: Optional[WeatherForecast], summary: str) -> str:
        forecast_text = ""
        if forecast and forecast.days:
            lines = [f"  Day {i+1} ({d.date_str}): {d.description}, {d.max_temp_c:.0f}°C high, {d.precipitation_mm:.0f}mm rain"
                     for i, d in enumerate(forecast.days[:7])]
            forecast_text = "\n".join(lines)

        return (
            f"{SYSTEM_CONTEXT}\n\n"
            f"Destination: {request.destination}\n"
            f"Travel dates: {request.start_date} to {request.end_date}\n"
            f"Forecast summary: {summary}\n"
            f"Daily forecast:\n{forecast_text or 'Not available'}\n\n"
            f"Return JSON:"
        )

    def _parse_json(self, text: str) -> Optional[Dict]:
        try:
            start = text.find("{")
            end = text.rfind("}") + 1
            if start >= 0 and end > start:
                return json.loads(text[start:end])
        except Exception:
            pass
        return None

    def _fallback_assessment(self, forecast: Optional[WeatherForecast]) -> Dict:
        if forecast is None:
            return {
                "overall_assessment": "Weather data unavailable – check local forecasts before travel.",
                "safety_level": "good",
                "disruption_days": [],
                "recommendations": ["Check weather 48 hours before travel.", "Pack layers.", "Carry a rain poncho."],
                "alternative_suggestion": None,
            }
        disruptive = [i + 1 for i, d in enumerate(forecast.days) if d.is_disruptive]
        level = "avoid" if len(disruptive) > 3 else ("caution" if disruptive else "good")
        return {
            "overall_assessment": "Conditions look generally suitable for travel.",
            "safety_level": level,
            "disruption_days": disruptive,
            "recommendations": ["Carry an umbrella.", "Wear comfortable walking shoes.", "Stay hydrated in warm weather."],
            "alternative_suggestion": "Consider indoor activities on rainy days." if disruptive else None,
        }
